"""Doctor and specialty persistence contracts."""

import uuid
from typing import Protocol

from app.domain.models import DoctorModel, SpecialtyModel


class DoctorRepository(Protocol):
    def create(self, doctor: DoctorModel) -> DoctorModel: ...
    def get_by_id(self, doctor_id: uuid.UUID) -> DoctorModel | None: ...
    def list_active(self) -> list[DoctorModel]: ...
    def search(
        self,
        specialty: str | None = None,
        doctor_name: str | None = None,
        location: str | None = None,
        clinic_name: str | None = None,
        is_active: bool | None = True,
        limit: int = 10,
    ) -> list[DoctorModel]: ...
    def add_specialty(self, doctor_id: uuid.UUID, specialty_id: uuid.UUID) -> None: ...
    def get_specialties(self, doctor_id: uuid.UUID) -> list[SpecialtyModel]: ...


class SpecialtyRepository(Protocol):
    def create(self, specialty: SpecialtyModel) -> SpecialtyModel: ...
    def get_by_id(self, specialty_id: uuid.UUID) -> SpecialtyModel | None: ...
    def get_by_name(self, name: str) -> SpecialtyModel | None: ...
    def list_all(self) -> list[SpecialtyModel]: ...
